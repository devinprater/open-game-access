#!/usr/bin/env python3
"""n64-android-cmake.py -- write the Android CMake subproject for the
Nintendo 64 core (Mupen64Plus-Next) from the AUDITED source list.

Called by scripts/android-apply-overlay.sh section 10c, and runnable on its
own so the same file can be built on the host (scripts/n64-android-cmake-test.sh).

The list, the defines and the include roots all come from
scripts/core-sources.sh (M64P_ALL, M64P_OGA_C, M64P_DEFS, m64p_inc), the
same place the iOS builds and the host proof read them from, so the three
builds cannot drift apart. Layout the generated file expects (the overlay
stages it):

    <n64-dir>/src/           the pinned Mupen64Plus-Next tree
    <n64-dir>/glue/          Core/n64_core.cpp, Core/*.h, Core/n64/,
                             Core/n64_m64p_stubs.c
    <n64-dir>/gen/           m64p-isolate.sh, m64p-archive.sh, oga_n64_empty.cpp

Two libraries come out of it:

    oga-m64p (an archive file, not a CMake target): every core object
        renamed with the oga_m64p_ prefix by scripts/m64p-isolate.sh, the
        pass the iOS builds run, packed by scripts/m64p-archive.sh.
    oga-n64-glue: Core/n64_core.cpp, the wrapper, which calls the core as
        oga_m64p_retro_*. It carries the archive as an INTERFACE link
        dependency, so a target that links the glue gets the core too, in
        the right order.

armeabi-v7a gets an empty glue library and no core, like the other 64-bit
only consoles (sections 8 to 10b of the overlay).

Usage: n64-android-cmake.py <core-sources.sh> <out CMakeLists.txt> <n64-dir>
"""
import os
import re
import subprocess
import sys


def main():
    sources_sh, out_path, n64_dir = sys.argv[1:4]
    text = open(sources_sh, encoding="utf-8").read()

    def var(name):
        m = re.search(r'^%s="(.*?)"' % name, text, re.S | re.M)
        assert m, "no %s in %s" % (name, sources_sh)
        return m.group(1).split()

    files = var("M64P_ALL")
    oga = var("M64P_OGA_C")
    assert files, "M64P_ALL came back empty -- refusing to write a broken CMakeLists"
    assert oga, "M64P_OGA_C came back empty -- the GLideN64 stubs would be missing"
    flags = var("M64P_DEFS")
    defs = [f[2:] for f in flags if f.startswith("-D")]
    opts = [f for f in flags if not f.startswith("-D")]

    # m64p_inc is a shell function; ask the shell, with markers for the two
    # roots, and map them onto the staged layout.
    inc = subprocess.check_output(
        ["bash", "-c", 'source "$0" && m64p_inc @SRC@ @ROOT@', sources_sh],
        text=True).split()
    includes, forced = [], []
    i = 0
    while i < len(inc):
        tok = inc[i]
        if tok == "-include":
            forced.append(inc[i + 1])
            i += 2
            continue
        assert tok.startswith("-I"), "unexpected m64p_inc token: " + tok
        includes.append(tok[2:])
        i += 1

    def place(path):
        path = path.replace("@ROOT@/Core", "${CMAKE_CURRENT_SOURCE_DIR}/glue")
        path = path.replace("@SRC@", "${M64P_SRC_DIR}")
        assert "@" not in path, "unmapped include root: " + path
        return path

    tree = os.path.join(n64_dir, "src")
    for f in files:
        assert os.path.isfile(os.path.join(tree, f)), \
            "missing from the Mupen64Plus-Next tree: " + f
    for f in oga:
        assert os.path.isfile(os.path.join(n64_dir, "glue", f)), \
            "missing from the staged glue: " + f

    c_files = [f for f in files if f.endswith(".c")]
    cxx_files = [f for f in files if f.endswith(".cpp")]
    assert len(c_files) + len(cxx_files) == len(files), "a source is neither .c nor .cpp"

    out = []
    w = out.append
    w("""# Generated by scripts/n64-android-cmake.py -- do not edit.
#
# Mupen64Plus-Next (the Nintendo 64 core) plus the OGA wrapper for it,
# built from the AUDITED source list in scripts/core-sources.sh (M64P_ALL),
# with the defines the iOS build uses. See the overlay's section 10c.

cmake_minimum_required(VERSION 3.22)
project(oga-n64 C CXX)

if (CMAKE_ANDROID_ARCH_ABI STREQUAL "armeabi-v7a")
    add_library(oga-n64-glue STATIC gen/oga_n64_empty.cpp)
else ()
    set(M64P_SRC_DIR ${CMAKE_CURRENT_SOURCE_DIR}/src)
    set(M64P_SOURCES
""")
    for f in c_files + cxx_files:
        w("        ${M64P_SRC_DIR}/%s\n" % f)
    for f in oga:
        w("        ${CMAKE_CURRENT_SOURCE_DIR}/glue/%s\n" % f)
    w("    )\n    set(OGA_M64P_INC\n")
    for p in includes:
        w("        %s\n" % place(p))
    w("    )\n    set(OGA_M64P_DEFS\n")
    for d in defs + ["OS_LINUX", "HAVE_POSIX_MEMALIGN=1"]:
        w("        %s\n" % d)
    w("    )\n    set(OGA_M64P_OPTS -w")
    for o in opts:
        w(" %s" % o)
    for f in forced:
        w(' "SHELL:-include %s"' % place(f))
    w(")\n")
    w("""
    # The core, as objects: they are renamed before anything links them.
    add_library(oga-m64p-obj OBJECT ${M64P_SOURCES})
    set_target_properties(oga-m64p-obj PROPERTIES
        C_STANDARD 11 C_EXTENSIONS ON
        CXX_STANDARD 11 CXX_EXTENSIONS ON
        POSITION_INDEPENDENT_CODE ON)
    target_include_directories(oga-m64p-obj PRIVATE ${OGA_M64P_INC})
    target_compile_definitions(oga-m64p-obj PRIVATE ${OGA_M64P_DEFS})
    target_compile_options(oga-m64p-obj PRIVATE ${OGA_M64P_OPTS})

    if (NOT CMAKE_NM)
        find_program(CMAKE_NM NAMES llvm-nm nm)
    endif ()
    if (NOT CMAKE_OBJCOPY)
        find_program(CMAKE_OBJCOPY NAMES llvm-objcopy objcopy)
    endif ()
    if (NOT CMAKE_AR)
        find_program(CMAKE_AR NAMES llvm-ar ar)
    endif ()

    # Every core global becomes oga_m64p_<name> (scripts/m64p-isolate.sh,
    # the pass the iOS builds run), and the pass re-proves it.
    set(OGA_M64P_ARCHIVE ${CMAKE_CURRENT_BINARY_DIR}/liboga-m64p.a)
    add_custom_command(
        OUTPUT ${OGA_M64P_ARCHIVE}
        COMMAND bash ${CMAKE_CURRENT_SOURCE_DIR}/gen/m64p-archive.sh
                ${OGA_M64P_ARCHIVE} ${CMAKE_AR} ${CMAKE_NM} ${CMAKE_OBJCOPY}
                ${CMAKE_CURRENT_SOURCE_DIR}/gen/m64p-isolate.sh
                $<TARGET_OBJECTS:oga-m64p-obj>
        DEPENDS oga-m64p-obj $<TARGET_OBJECTS:oga-m64p-obj>
                ${CMAKE_CURRENT_SOURCE_DIR}/gen/m64p-archive.sh
                ${CMAKE_CURRENT_SOURCE_DIR}/gen/m64p-isolate.sh
        COMMAND_EXPAND_LISTS
        VERBATIM)
    add_custom_target(oga-m64p-isolated DEPENDS ${OGA_M64P_ARCHIVE})

    add_library(oga-n64-glue STATIC ${CMAKE_CURRENT_SOURCE_DIR}/glue/n64_core.cpp)
    set_target_properties(oga-n64-glue PROPERTIES CXX_STANDARD 17)
    target_include_directories(oga-n64-glue PRIVATE
        ${CMAKE_CURRENT_SOURCE_DIR}/glue
        ${M64P_SRC_DIR}/libretro-common/include)
    target_compile_options(oga-n64-glue PRIVATE -w)
    add_dependencies(oga-n64-glue oga-m64p-isolated)
    # Glue first, core behind it: its oga_m64p_* references resolve there.
    target_link_libraries(oga-n64-glue INTERFACE ${OGA_M64P_ARCHIVE})
endif ()
""")
    open(out_path, "w", encoding="utf-8").write("".join(out))
    print("     generated the Nintendo 64 build (%d audited core sources + %d OGA stubs + glue)"
          % (len(files), len(oga)))


if __name__ == "__main__":
    main()
